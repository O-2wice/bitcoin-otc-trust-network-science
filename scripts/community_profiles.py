"""Describe the five largest existing Louvain groups using positive links.

Run structural_analysis.py first, then python scripts/community_profiles.py.
Groups are structural partitions without account metadata or social labels.
"""

import json
from pathlib import Path

import matplotlib.pyplot as plt
import networkx as nx
import pandas as pd

from structural_analysis import load_graphs


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs" / "sensitivity"


def main():
    _, _, graph = load_graphs()
    assignments = pd.read_csv(ROOT / "outputs" / "structure" / "communities.csv")
    assert assignments.node.is_unique and set(assignments.node) == set(graph)
    membership = dict(zip(assignments.node, assignments.community))
    groups = assignments.groupby("community").size().sort_values(ascending=False)
    rows = []
    for rank, (community, size) in enumerate(groups.head(5).items(), start=1):
        users = set(assignments.loc[assignments.community == community, "node"])
        internal = graph.subgraph(users).number_of_edges()
        boundary = sum(1 for u, v in graph.edges if (u in users) != (v in users))
        endpoints = sum(graph.degree(u) for u in users)
        assert endpoints == 2 * internal + boundary
        most_connected = min(users, key=lambda u: (-graph.degree(u), u))
        rows.append({
            "group_rank_by_size": rank, "louvain_group_id": int(community),
            "users": int(size), "internal_links": internal, "boundary_links": boundary,
            "total_link_endpoints_at_group": endpoints,
            "within_group_endpoint_fraction": 2 * internal / endpoints,
            "boundary_endpoint_fraction": boundary / endpoints,
            "internal_density": 2 * internal / (size * (size - 1)),
            "mean_projected_degree": endpoints / size,
            "most_connected_user_id": int(most_connected),
            "most_connected_user_projected_degree": graph.degree(most_connected),
        })
    result = pd.DataFrame(rows)
    assert result.within_group_endpoint_fraction.between(0, 1).all()
    assert (result.within_group_endpoint_fraction + result.boundary_endpoint_fraction).sub(1).abs().max() < 1e-12
    isolated = nx.number_of_isolates(graph)
    largest = len(max(nx.connected_components(graph), key=len))
    metadata = {
        "graph": "Simple undirected positive projection, all 5881 observed accounts; no sign, rating magnitude, or direction",
        "groups": "Existing single-seed Louvain assignment generated by structural_analysis.py; five groups selected by size",
        "within_group_endpoint_fraction": "2 * internal links / (2 * internal links + links from the group to other groups)",
        "interpretation": "Fraction of link endpoints in a group whose other endpoint lies in the same group; links are counted at each endpoint. Louvain optimizes related within-group connectivity, so this description is not an independent validation.",
        "limits": "Anonymous account IDs provide no occupational, trading, or geographic community labels. Partition stability across seeds was not assessed.",
        "total_components": nx.number_connected_components(graph),
        "isolated_accounts_after_positive_filter": isolated,
        "nonisolated_accounts": len(graph) - isolated,
        "largest_component_accounts": largest,
        "largest_component_fraction_all_accounts": largest / len(graph),
        "largest_component_fraction_nonisolated_accounts": largest / (len(graph) - isolated),
    }
    OUT.mkdir(parents=True, exist_ok=True)
    result.to_csv(OUT / "community_profiles.csv", index=False)
    (OUT / "community_metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")

    plt.style.use("seaborn-v0_8-whitegrid")
    labels = [f"Group {row.group_rank_by_size}\n{row.users:,} users" for row in result.itertuples()]
    within = 100 * result.within_group_endpoint_fraction
    boundary = 100 * result.boundary_endpoint_fraction
    fig, ax = plt.subplots(figsize=(7.3, 4.3))
    ax.bar(labels, within, color="#D99A36", label="Other endpoint in same group")
    ax.bar(labels, boundary, bottom=within, color="#287D8E", label="Other endpoint in another group")
    for i, value in enumerate(within):
        ax.text(i, value / 2, f"{value:.1f}%", ha="center", va="center", color="#132B3F")
    ax.set(ylabel="Link endpoints at group members (%)", ylim=(0, 100),
           title="How internally connected are the largest Louvain groups?")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.18), ncol=1, fontsize=8)
    fig.tight_layout()
    fig.savefig(OUT / "community_link_profiles.png", dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(result.round(4).to_string(index=False))
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
